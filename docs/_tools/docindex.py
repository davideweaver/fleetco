#!/usr/bin/env python3
"""Validate docs frontmatter and regenerate docs/README.md.

    python3 docs/_tools/docindex.py          # check + regenerate the index
    python3 docs/_tools/docindex.py --check  # check only, non-zero exit on error
    python3 docs/_tools/docindex.py --touch <path>...  # set updated: to today on the named docs

Run from the repository root. The index is generated — never edit docs/README.md by hand.
"""
import datetime as dt
import glob
import io
import os
import re
import sys

STATUSES = {
    "current":    "The plan of record. Trust it",
    "living":     "Current, and expected to keep changing",
    "decided":    "A closed decision, kept for the reasoning",
    "reference":  "Findings that remain true. Not a plan, not a decision",
    "draft":      "Being written. Do not rely on it",
    "superseded": "History. Carries `superseded_by`",
    "artifact":   "A record of a moment — meeting, transcript, audit, prompt. Never updated",
}
ORDER = ["current", "living", "decided", "reference", "draft", "artifact", "superseded"]
STALE_DAYS = 90
DOCS = "docs"


def frontmatter(path):
    s = io.open(path, encoding="utf-8").read()
    if not s.startswith("---\n") or "\n---" not in s[4:]:
        return None
    fm = s[4:s.index("\n---", 4)]
    out = {}
    for m in re.finditer(r"^(\w+):\s*(.*)$", fm, re.M):
        out[m.group(1)] = m.group(2).strip()
    return out


def collect():
    docs = []
    for f in sorted(glob.glob(f"{DOCS}/**/*.md", recursive=True)):
        if "/_tools/" in f or f == f"{DOCS}/README.md":
            continue
        docs.append((f, frontmatter(f)))
    return docs


def check(docs):
    errors, warnings = [], []
    names = {os.path.splitext(os.path.basename(f))[0] for f, _ in docs}
    today = dt.date.today()
    for f, fm in docs:
        rel = f[len(DOCS) + 1:]
        if fm is None:
            errors.append(f"{rel}: no frontmatter")
            continue
        st = fm.get("status")
        if not st:
            errors.append(f"{rel}: no status")
        elif st not in STATUSES:
            errors.append(f"{rel}: status '{st}' is not one of {', '.join(STATUSES)}")
        if not fm.get("updated"):
            errors.append(f"{rel}: no updated date")
        if not fm.get("summary"):
            warnings.append(f"{rel}: no summary, so it will read blank in the index")
        if st == "superseded" and not fm.get("superseded_by"):
            errors.append(f"{rel}: superseded but no superseded_by")
        sb = fm.get("superseded_by")
        if sb and sb not in names:
            errors.append(f"{rel}: superseded_by '{sb}' does not match any doc")
        # broken wikilinks
        body = io.open(f, encoding="utf-8").read()
        for m in re.findall(r"\[\[([^\]#|]+)(?:[#|][^\]]*)?\]\]", body):
            t = m.strip()
            if t and t not in names and "/" not in t:
                warnings.append(f"{rel}: wikilink [[{t}]] matches no doc")
        # staleness
        if st == "current" and fm.get("updated"):
            try:
                age = (today - dt.date.fromisoformat(fm["updated"])).days
                if age > STALE_DAYS:
                    warnings.append(f"{rel}: marked current but untouched for {age} days")
            except ValueError:
                errors.append(f"{rel}: updated '{fm['updated']}' is not YYYY-MM-DD")
    return errors, warnings


def render(docs):
    by_status = {s: [] for s in ORDER}
    for f, fm in docs:
        if fm and fm.get("status") in by_status:
            by_status[fm["status"]].append((f, fm))
    today = dt.date.today().isoformat()
    out = [
        "<!-- GENERATED by docs/_tools/docindex.py — do not edit by hand. -->",
        "",
        "# Fleetco docs",
        "",
        f"{len(docs)} documents. Generated {today}.",
        "",
        "**Read this first to find out what is true.** Every document carries a `status`:",
        "",
        "| Status | Means |",
        "|---|---|",
    ]
    for s in ORDER:
        out.append(f"| `{s}` | {STATUSES[s]} |")
    out += ["", "Regenerate with `python3 docs/_tools/docindex.py`.", ""]
    for s in ORDER:
        rows = by_status[s]
        if not rows:
            continue
        out += [f"## {s} — {len(rows)}", "", f"*{STATUSES[s]}.*", "",
                "| Doc | What it is | Updated |", "|---|---|---|"]
        for f, fm in rows:
            rel = f[len(DOCS) + 1:]
            name = os.path.splitext(os.path.basename(f))[0]
            extra = ""
            if fm.get("superseded_by"):
                extra = f" → **[[{fm['superseded_by']}]]**"
            out.append(f"| [{name}]({rel.replace(' ', '%20')}) | {fm.get('summary','')}{extra} | {fm.get('updated','')} |")
        out.append("")
    return "\n".join(out) + "\n"


def touch(paths):
    """Bump `updated:` to today on the named docs.

    Deliberately takes explicit paths. An earlier version bumped everything git saw as
    changed, which marked all 59 docs updated on the same day and destroyed the staleness
    signal the index exists to provide. `updated` means the content changed, not the file.
    """
    today = dt.date.today().isoformat()
    for p in paths:
        if not p.endswith(".md"):
            print(f"skip  {p}: not a .md file")
            continue
        try:
            s = io.open(p, encoding="utf-8").read()
        except FileNotFoundError:
            print(f"skip  {p}: not found")
            continue
        s2 = re.sub(r"^updated: .*$", f"updated: {today}", s, count=1, flags=re.M)
        if s2 != s:
            io.open(p, "w", encoding="utf-8").write(s2)
            print(f"touched {p}")


def main():
    if "--touch" in sys.argv:
        paths = [a for a in sys.argv[sys.argv.index("--touch") + 1:] if not a.startswith("--")]
        if not paths:
            print("usage: docindex.py --touch <path>...")
            sys.exit(2)
        touch(paths)
    docs = collect()
    errors, warnings = check(docs)
    for w in warnings:
        print(f"warn  {w}")
    for e in errors:
        print(f"ERROR {e}")
    if "--check" in sys.argv:
        print(f"\n{len(docs)} docs · {len(errors)} errors · {len(warnings)} warnings")
        sys.exit(1 if errors else 0)
    io.open(f"{DOCS}/README.md", "w", encoding="utf-8").write(render(docs))
    print(f"\nwrote {DOCS}/README.md · {len(docs)} docs · {len(errors)} errors · {len(warnings)} warnings")
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
